CREATE INDEX "IX_ProductVariants_Sku_Trgm" ON public."ProductVariants" USING gin ("Sku" public.gin_trgm_ops);

CREATE INDEX "IX_Products_BrandId" ON public."Products" USING btree ("BrandId");

CREATE INDEX "IX_Products_CategoryId" ON public."Products" USING btree ("CategoryId");

CREATE INDEX "IX_Products_Name_Trgm" ON public."Products" USING gin ("Name" public.gin_trgm_ops);

CREATE INDEX "IX_Products_Status" ON public."Products" USING btree ("Status");

