CREATE INDEX "IX_Products_Status_CategoryId" ON public."Products" USING btree ("Status", "CategoryId");

CREATE INDEX "IX_Products_Status_IsPopular_IsNew" ON public."Products" USING btree ("Status", "IsPopular", "IsNew");

