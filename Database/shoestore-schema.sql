    "Name" public.citext NOT NULL,
    "Sku" public.citext NOT NULL,
    "Swatch" character varying(24) NOT NULL,
    "ImageUrl" character varying(512) NOT NULL,
    "IsDefault" boolean NOT NULL,
    "ThumbnailUrl" character varying(512)
);

ALTER TABLE public."ProductVariants" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."ProductVariants_Id_seq"
