ALTER TABLE public."ProductVariantImages" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."ProductVariantImages_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."ProductVariantSizes" (
    "Id" integer NOT NULL,
    "ProductVariantId" integer NOT NULL,
    "Size" integer NOT NULL,
    "StockQuantity" integer NOT NULL,
    CONSTRAINT "CK_ProductVariantSizes_Size" CHECK ((("Size" >= 30) AND ("Size" <= 50))),
    CONSTRAINT "CK_ProductVariantSizes_Stock" CHECK ((("StockQuantity" >= 0) AND ("StockQuantity" <= 999)))
);

ALTER TABLE public."ProductVariantSizes" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."ProductVariantSizes_Id_seq"
