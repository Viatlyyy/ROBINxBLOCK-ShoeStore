ALTER TABLE public."Categories" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."Categories_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."Favorites" (
    "Id" integer NOT NULL,
    "UserId" character varying(450) NOT NULL,
    "ProductId" integer NOT NULL,
    "CreatedAt" timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
);

ALTER TABLE public."Favorites" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."Favorites_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."OrderItems" (
    "Id" integer NOT NULL,
    "OrderId" integer NOT NULL,
    "ProductId" integer NOT NULL,
    "ProductVariantId" integer NOT NULL,
    "ProductName" character varying(180) NOT NULL,
    "VariantName" character varying(80) NOT NULL,
    "Sku" character varying(64) NOT NULL,
    "Size" integer NOT NULL,
    "Quantity" integer NOT NULL,
    "Price" numeric(10,2) NOT NULL,
    "ImageUrl" character varying(512) DEFAULT ''::character varying NOT NULL,
    CONSTRAINT "CK_OrderItems_Price" CHECK (("Price" > (0)::numeric)),
    CONSTRAINT "CK_OrderItems_Quantity" CHECK (("Quantity" > 0)),
    CONSTRAINT "CK_OrderItems_Size" CHECK ((("Size" >= 30) AND ("Size" <= 50)))
);

ALTER TABLE public."OrderItems" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."OrderItems_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."Orders" (
    "Id" integer NOT NULL,
    "UserId" text,
    "CustomerName" character varying(80) NOT NULL,
    "Phone" character varying(32) NOT NULL,
    "DeliveryMethod" character varying(32) NOT NULL,
    "Status" character varying(24) NOT NULL,
    "CreatedAt" timestamp with time zone NOT NULL,
    "Total" numeric(10,2) NOT NULL,
    "Apartment" character varying(20),
    "City" character varying(80),
    "Comment" character varying(500),
    "Email" character varying(254),
    "House" character varying(20),
    "LastName" character varying(80),
    "PaymentMethod" character varying(24) DEFAULT 'cash'::character varying NOT NULL,
    "Postcode" character varying(12),
    "PublicId" uuid DEFAULT gen_random_uuid() NOT NULL,
    "Street" character varying(120),
    CONSTRAINT "CK_Orders_Total" CHECK (("Total" >= (0)::numeric))
);

ALTER TABLE public."Orders" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."Orders_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."ProductVariantImages" (
    "Id" integer NOT NULL,
    "ProductVariantId" integer NOT NULL,
    "ImageUrl" character varying(512) NOT NULL,
    "SortOrder" integer NOT NULL,
    "ThumbnailUrl" character varying(512)
