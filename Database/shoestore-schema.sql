CREATE UNIQUE INDEX "IX_Brands_Name" ON public."Brands" USING btree ("Name");

CREATE INDEX "IX_Brands_Name_Trgm" ON public."Brands" USING gin ("Name" public.gin_trgm_ops);

CREATE INDEX "IX_CatalogAuditLogs_CreatedAt" ON public."CatalogAuditLogs" USING btree ("CreatedAt" DESC);

CREATE UNIQUE INDEX "IX_Categories_Name" ON public."Categories" USING btree ("Name");

CREATE UNIQUE INDEX "IX_Favorites_UserId_ProductId" ON public."Favorites" USING btree ("UserId", "ProductId");

