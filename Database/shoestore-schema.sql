    "SecurityStamp" text,
    "ConcurrencyStamp" text,
    "PhoneNumber" text,
    "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamp with time zone,
    "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL,
    "AvatarUrl" text,
    "DisplayName" character varying(80)
);

CREATE TABLE public."Brands" (
    "Id" integer NOT NULL,
    "Name" public.citext NOT NULL,
    "Description" text
);

ALTER TABLE public."Brands" ALTER COLUMN "Id" ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public."Brands_Id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public."CatalogAuditLogs" (
    "Id" integer NOT NULL,
    "EntityType" character varying(40) NOT NULL,
    "EntityId" integer NOT NULL,
    "Action" character varying(60) NOT NULL,
    "Summary" character varying(300) NOT NULL,
    "ActorUserId" text,
